// 그물 — 반드시 0이어야 하는 것들만 본다
export function 그물(m) {
  if (!m) return null;
  const 걸림 = DASH_ITEMS.filter(i => i.hard && i.warn(m[i.key] ?? 0, m));
  return { 통과: !걸림.length, 사유: 걸림.map(i => i.label) };
}

