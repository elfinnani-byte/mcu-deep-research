// 보고서 조판 — 본문과 출처를 갈라 놓는다.
//
// 기자는 문장 끝에 «문서 제목» 을 달아 근거를 남긴다. 그게 이 보고서의 값어치인데,
// 제목이 문장 사이에 그대로 박혀 있으면 읽기가 어렵다.
// 그래서 **본문에는 번호만 두고, 문서 제목은 맨 끝 「참고자료」로 모은다.**
//
//   본문   … 여섯 개의 가상의 아이템입니다.[1] 각 스톤은 특정한 힘을 지닙니다.[1]
//   참고   [1] Infinity Stones
//
// ⚠ 절 본문 자체는 건드리지 않는다. ⑥ 평가의 「근거가 달린 문장」은 상태에 있는
//    절 본문(«» 가 그대로 있는 것)을 세므로 지표는 이 조판의 영향을 받지 않는다.
//
// 이 파일은 파이프라인(만들 때)과 화면(볼 때) 둘 다 쓴다. 규칙은 한 곳에만 둔다.

const 참고제목 = /\n##\s*참고자료\s*\n/;

/** 보고서 한 장을 { 본문, 참고 } 로 가른다. 이미 갈라져 있으면 그대로 돌려준다(멱등). */
export function 조판(md = '') {
  const i = md.search(참고제목);
  if (i >= 0) {                                   // 이미 참고자료가 붙어 있다
    return {
      본문: md.slice(0, i).trimEnd(),
      참고: [...md.slice(i).matchAll(/^\[(\d+)\]\s+(.+)$/gm)].map(m => m[2].trim()),
    };
  }
  const 참고 = [];
  // 문장 **첫머리**에 붙은 인용은 번호만 남기면 주어가 숫자가 된다 —
  // 실제로 「[8]는 MCU의 세 번째 페이즈에 속합니다」 가 나왔다. 그럴 때는 제목을 남긴다.
  const 본문 = md.replace(/([ \t]*)«([^»]+)»/g, (_, 앞공백, 제목, 자리) => {
    const t = 제목.trim();
    let n = 참고.indexOf(t);
    if (n < 0) { 참고.push(t); n = 참고.length - 1; }
    const 앞 = md.slice(0, 자리).replace(/[ \t]+$/, '');
    const 첫머리 = !앞.trim() || /[\n.!?:]$/.test(앞);
    return 첫머리 ? `${앞공백}「${t}」[${n + 1}]` : `[${n + 1}]`;
  });
  return { 본문: 본문.trimEnd(), 참고 };
}

/** 참고자료 블록. 출처가 없으면 빈 문자열 — 없는 섹션을 만들지 않는다. */
export const 참고블록 = (참고 = []) =>
  참고.length ? `\n\n## 참고자료\n\n${참고.map((d, i) => `[${i + 1}] ${d}`).join('\n')}` : '';

/** 저장용 한 장 — 본문 + 참고자료 */
export const 합치기 = ({ 본문, 참고 }) => 본문 + 참고블록(참고);

/** **보고서 글자수는 참고자료를 뺀 본문만 센다.** */
export const 본문자수 = md => 조판(md).본문.length;
